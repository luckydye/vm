//! Running VMs as ssh hosts named `vm-NAME`, for ssh, scp and tools that list
//! the hosts of ~/.ssh/config, such as OpenCode Desktop.
//!
//! `~/.vm/ssh_config` holds a host for every VM with an `ssh_host` file in its
//! directory. A VM process creates that file when it starts and removes it when
//! it exits, rewriting the config whole each time; `prune` removes the files of
//! VMs that were killed. ~/.ssh/config includes the generated config, and the
//! first registration adds that `Include` at its top.

use crate::instance::{self, Instance};
use std::{
    env,
    fmt::Write as _,
    fs::{self, File, OpenOptions},
    io,
    os::unix::fs::{DirBuilderExt, OpenOptionsExt, PermissionsExt},
    path::{Path, PathBuf},
};

pub const HOST_PREFIX: &str = "vm-";

pub fn config_path() -> PathBuf {
    instance::home().join("ssh_config")
}

fn marker(dir: &Path) -> PathBuf {
    dir.join("ssh_host")
}

/// Serializes rewrites of the generated config and of ~/.ssh/config.
fn lock() -> io::Result<File> {
    let lock = File::create(instance::home().join("ssh_config.lock"))?;
    lock.lock()?;
    Ok(lock)
}

/// Lists the VM in `dir` as an ssh host.
pub fn register(dir: &Path) -> io::Result<()> {
    let _lock = lock()?;
    fs::write(marker(dir), "")?;
    include()?;
    write()
}

/// Removes the VM in `dir` from the ssh hosts, if it is listed.
pub fn unregister(dir: &Path) -> io::Result<()> {
    let _lock = lock()?;
    match fs::remove_file(marker(dir)) {
        Ok(()) => write(),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error),
    }
}

/// Removes the hosts of VMs that no longer run. The caller holds the registry
/// lock, so no VM is created or deleted meanwhile.
pub fn prune(instances: &[Instance]) -> io::Result<()> {
    let _lock = lock()?;
    for instance in instances {
        if marker(&instance.dir).exists() && !instance.is_running() {
            fs::remove_file(marker(&instance.dir))?;
        }
    }
    write()
}

/// Rewrites the generated config from the listed VMs.
fn write() -> io::Result<()> {
    let vm = env::current_exe()?.canonicalize()?;
    let home = instance::home();
    let key = instance::ssh_key();
    for path in [&vm, &home, &key] {
        assert!(!path.to_string_lossy().contains(['\'', '"']), "quotes in {} break the ssh config", path.display());
    }
    let mut config = String::from("# Running VMs, generated by vm; changes are overwritten.\n");
    for instance in instance::list() {
        if !marker(&instance.dir).exists() {
            continue;
        }
        let name = &instance.name;
        write!(
            config,
            "\nHost {HOST_PREFIX}{name}\n    \
             User varmint\n    \
             IdentityFile \"{key}\"\n    \
             ProxyCommand env VM_HOME='{home}' '{vm}' proxy {name} 22\n    \
             StrictHostKeyChecking no\n    \
             UserKnownHostsFile /dev/null\n    \
             LogLevel ERROR\n",
            key = key.display(),
            home = home.display(),
            vm = vm.display(),
        )
        .unwrap();
    }
    replace(&config_path(), config.as_bytes(), 0o644)
}

/// Adds `Include` of the generated config at the top of ~/.ssh/config, where
/// it applies to every host, unless it is there already.
fn include() -> io::Result<()> {
    let ssh_dir = PathBuf::from(env::var_os("HOME").expect("HOME is not set")).join(".ssh");
    fs::DirBuilder::new().recursive(true).mode(0o700).create(&ssh_dir)?;
    // Follow a symlinked config, as dotfile managers make, instead of replacing it.
    let path = match ssh_dir.join("config").canonicalize() {
        Ok(path) => path,
        Err(error) if error.kind() == io::ErrorKind::NotFound => ssh_dir.join("config"),
        Err(error) => return Err(error),
    };
    let (existing, mode) = match fs::read_to_string(&path) {
        Ok(existing) => (existing, fs::metadata(&path)?.permissions().mode() & 0o777),
        Err(error) if error.kind() == io::ErrorKind::NotFound => (String::new(), 0o600),
        Err(error) => return Err(error),
    };
    let line = format!("Include \"{}\"", config_path().display());
    if existing.lines().any(|existing| existing.trim() == line) {
        return Ok(());
    }
    replace(&path, format!("{line}\n\n{existing}").as_bytes(), mode)
}

/// Replaces `path` atomically, so ssh never reads a partial file.
fn replace(path: &Path, contents: &[u8], mode: u32) -> io::Result<()> {
    let partial = path.with_file_name(format!(".{}.partial", path.file_name().unwrap().to_string_lossy()));
    let mut file = OpenOptions::new().write(true).create(true).truncate(true).mode(mode).open(&partial)?;
    io::Write::write_all(&mut file, contents)?;
    file.set_permissions(fs::Permissions::from_mode(mode))?;
    file.sync_all()?;
    fs::rename(&partial, path)
}
